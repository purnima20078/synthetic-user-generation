export function convertQAToPersona(item: QAPersonaItem, workspaceId: string): Persona {
  return {
    _id: `per_${item.id}`,
    workspace_id: workspaceId,
    name: item.name,
    age: item.age,
    gender: item.gender,
    occupation: item.occupation,
    location: item.location,
    income_level: item.income,
    education: item.occupation.includes('Student') ? 'Undergraduate' : item.occupation.includes('Engineer') ? 'B.Tech / Engineering' : 'Graduate',
    marital_status: item.age > 28 ? 'Married' : 'Single',
    segment: item.occupation.includes('Student') ? 'Students & Youth' : item.occupation.includes('Engineer') || item.occupation.includes('Designer') ? 'Young Urban Pros' : item.occupation.includes('Business') ? 'Small Business Owners' : 'Young Working Professionals',
    avatar_seed: item.name.toLowerCase().replace(/[^a-z0-9]/g, '_'),
    backstory: item.backstory,
    quote: item.quote,
    created_at: new Date().toISOString(),
    personality_traits: {
      ocean: {
        openness: 72,
        conscientiousness: 68,
        extraversion: 60,
        agreeableness: 70,
        neuroticism: 35,
      },
      archetype: item.personality.archetype,
      labels: item.personality.traits,
    },
    behaviour: {
      shopping_habits: item.behaviour.shoppingHabits,
      decision_style: item.personality.decisionStyle,
      tech_savviness: item.behaviour.techSavviness,
      brand_loyalty: item.behaviour.brandLoyalty as any,
      price_sensitivity: item.priceSensitivity === 'Very High Price' ? 'Bargain Hunter' : item.priceSensitivity === 'High Price' ? 'Value-Driven' : item.priceSensitivity === 'Moderate Price' ? 'Quality-First' : 'Insensitive',
      media_channels: ['Instagram', 'WhatsApp', 'YouTube', 'Nykaa'],
    },
    psych_profile: {
      motivations: [
        '100% toxin-free Ayurvedic skincare suitable for Indian weather',
        'Healthy glowing skin without harsh bleaching chemicals',
        'Visible dermatological improvement at honest pricing',
      ],
      frustrations: [
        'Chemical creams that feel sticky or greasy in humid Indian weather',
        'Brands that claim natural herbs but use artificial fragrances',
        'Overpriced imported cosmetics that do not address Indian skin conditions',
      ],
      values: ['Ayurvedic authenticity', 'Transparency', 'Holistic wellness', 'Value for money'],
      goals: ['Keep skin clear and protected from pollution and harsh sun', 'Support trustworthy toxin-free products'],
      fears: ['Allergic reactions to hidden parabens/sulfates', 'Wasting money on false advertising'],
    },
  };
}

